/**
 * Маппинг категорий → цвета для цветных меток (кружков).
 * Если категория не найдена, используется цвет по умолчанию.
 */
export const CATEGORY_COLORS = {
  'Еда': '#F59E0B',           // Оранжевый
  'Транспорт': '#3B82F6',     // Синий
  'Жилье': '#8B5CF6',         // Фиолетовый
  'Развлечения': '#EC4899',   // Розовый
  'Здоровье': '#10B981',      // Зелёный
  'Одежда': '#F97316',        // Оранжево-красный
  'Связь': '#06B6D4',         // Голубой
  'Прочее': '#9CA3AF',        // Серый
};

/**
 * Получает цвет для категории.
 * 
 * @param {string} categoryName - название категории
 * @returns {string} HEX цвет
 */
export const getCategoryColor = (categoryName) => {
  return CATEGORY_COLORS[categoryName] || '#9CA3AF'; // Серый по умолчанию
};